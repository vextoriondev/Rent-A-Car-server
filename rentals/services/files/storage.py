"""Object storage behind one small interface. Two implementations:

* S3Storage         : Cloudflare R2 / AWS S3 / any S3-compatible service (production, survives redeploys, works with Vercel + Railway)
* FilesystemStorage : a directory (PRIVATE_MEDIA_ROOT/attachments); development, or a single server with a mounted volume

Keys are generated by the server (org/entity/uuid/variant), never taken from the client, and every key is validated here
again so a bad key can never leave the storage root.
"""
import os
import re
import threading
from django.conf import settings

_KEY_OK = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_./-]{0,240}$')


def safe_key(key: str) -> str:
    if not _KEY_OK.match(key or '') or '..' in key or key.startswith('/') or '//' in key:
        raise ValueError('unsafe storage key')
    return key


class StorageError(Exception):
    pass


class FilesystemStorage:
    provider = 'filesystem'

    def __init__(self, root):
        self.root = os.path.realpath(str(root))
        os.makedirs(self.root, exist_ok=True)

    def _path(self, key):
        full = os.path.realpath(os.path.join(self.root, *safe_key(key).split('/')))
        if not full.startswith(self.root + os.sep):
            raise ValueError('unsafe storage key')
        return full

    def put(self, key, data: bytes, content_type: str):
        path = self._path(key)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + '.part'
        with open(tmp, 'wb') as f:
            f.write(data)
        os.replace(tmp, path)

    def get(self, key) -> bytes:
        try:
            with open(self._path(key), 'rb') as f:
                return f.read()
        except FileNotFoundError as e:
            raise StorageError('file is missing from storage') from e

    def delete(self, key):
        try:
            os.remove(self._path(key))
        except FileNotFoundError:
            pass

    def exists(self, key) -> bool:
        return os.path.isfile(self._path(key))

    def signed_url(self, key, filename, content_type, expires, download):
        return None          # no direct links: the API streams the bytes after its own permission check

    def mtime(self, key):
        try:
            return os.path.getmtime(self._path(key))
        except OSError:
            return None

    def iter_keys(self, prefix=''):
        base = self._path(prefix.rstrip('/')) if prefix else self.root
        for dirpath, _dirs, files in os.walk(base):
            for name in files:
                if not name.endswith('.part'):
                    yield os.path.relpath(os.path.join(dirpath, name), self.root).replace(os.sep, '/')


class S3Storage:
    provider = 's3'

    def __init__(self, bucket, prefix, client):
        self.bucket = bucket
        self.prefix = prefix.strip('/')
        self.client = client

    def _k(self, key):
        key = safe_key(key)
        return f'{self.prefix}/{key}' if self.prefix else key

    def put(self, key, data: bytes, content_type: str):
        try:
            self.client.put_object(Bucket=self.bucket, Key=self._k(key), Body=data, ContentType=content_type,
                                   CacheControl='private, max-age=31536000, immutable')
        except Exception as e:       # botocore errors: credentials, network, bucket
            raise StorageError(f'storage write failed: {type(e).__name__}') from e

    def get(self, key) -> bytes:
        try:
            return self.client.get_object(Bucket=self.bucket, Key=self._k(key))['Body'].read()
        except Exception as e:
            raise StorageError(f'storage read failed: {type(e).__name__}') from e

    def delete(self, key):
        try:
            self.client.delete_object(Bucket=self.bucket, Key=self._k(key))
        except Exception as e:
            raise StorageError(f'storage delete failed: {type(e).__name__}') from e

    def exists(self, key) -> bool:
        try:
            self.client.head_object(Bucket=self.bucket, Key=self._k(key))
            return True
        except Exception:
            return False

    def signed_url(self, key, filename, content_type, expires, download):
        disp = ('attachment' if download else 'inline') + '; filename="' + re.sub(r'[^A-Za-z0-9._ -]', '_', filename)[:120] + '"'
        return self.client.generate_presigned_url('get_object', ExpiresIn=expires, Params={
            'Bucket': self.bucket, 'Key': self._k(key), 'ResponseContentType': content_type, 'ResponseContentDisposition': disp})

    def mtime(self, key):
        try:
            return self.client.head_object(Bucket=self.bucket, Key=self._k(key))['LastModified'].timestamp()
        except Exception:
            return None

    def iter_keys(self, prefix=''):
        paginator = self.client.get_paginator('list_objects_v2')
        base = (self.prefix + '/' if self.prefix else '')
        for page in paginator.paginate(Bucket=self.bucket, Prefix=base + prefix):
            for obj in page.get('Contents', []):
                yield obj['Key'][len(base):]


_lock = threading.Lock()
_instance = None


def reset_storage():
    global _instance
    with _lock:
        _instance = None


def get_storage():
    global _instance
    with _lock:
        if _instance is None:
            if settings.FILE_STORAGE_BACKEND == 's3':
                import boto3
                from botocore.config import Config
                if not settings.S3_BUCKET:
                    raise StorageError('S3_BUCKET is not configured')
                client = boto3.client('s3', endpoint_url=settings.S3_ENDPOINT_URL or None, region_name=settings.S3_REGION or None,
                                      aws_access_key_id=settings.S3_ACCESS_KEY_ID or None, aws_secret_access_key=settings.S3_SECRET_ACCESS_KEY or None,
                                      config=Config(signature_version='s3v4', retries={'max_attempts': 3, 'mode': 'standard'}, s3={'addressing_style': 'path'}))
                _instance = S3Storage(settings.S3_BUCKET, settings.S3_KEY_PREFIX, client)
            else:
                _instance = FilesystemStorage(os.path.join(str(settings.PRIVATE_MEDIA_ROOT), 'attachments'))
        return _instance
